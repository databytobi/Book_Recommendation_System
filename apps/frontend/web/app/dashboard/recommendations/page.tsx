"use client";

import { useEffect, useState } from "react";
import { Sparkles, RefreshCw } from "lucide-react";

import {
  getRecommendations,
  type RecommendedBook,
} from "@/lib/services/recommendationService";

import RecommendationCard from "@/components/recommendations/RecommendationCard";

export default function RecommendationsPage() {
  const [books, setBooks] = useState<RecommendedBook[]>([]);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);

  const loadRecommendations = async () => {
    try {
      const response = await getRecommendations(20);
      setBooks(response.recommendations);
    } catch (error) {
      console.error("Failed to load recommendations:", error);
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  };

  useEffect(() => {
    loadRecommendations();
  }, []);

  const handleRefresh = async () => {
    setRefreshing(true);
    await loadRecommendations();
  };

  return (
    <div className="space-y-8">
      {/* Header */}
      <div className="flex items-start justify-between">
        <div>
          <div className="mb-3 flex items-center gap-2">
            <Sparkles className="h-6 w-6 text-primary" />
            <span className="rounded-full bg-primary/10 px-3 py-1 text-xs font-semibold text-primary">
              AI Powered
            </span>
          </div>

          <h1 className="text-3xl font-bold tracking-tight">
            Personalized Recommendations
          </h1>

          <p className="mt-2 max-w-2xl text-muted-foreground">
            These books are generated by your Hybrid Recommendation Engine using
            content similarity, favorite authors, genres, reading style, and
            collaborative signals.
          </p>
        </div>

        <button
          onClick={handleRefresh}
          disabled={refreshing}
          className="flex items-center gap-2 rounded-lg border px-4 py-2 text-sm hover:bg-muted disabled:opacity-50"
        >
          <RefreshCw
            className={`h-4 w-4 ${refreshing ? "animate-spin" : ""}`}
          />
          Refresh
        </button>
      </div>

      {/* Stats */}
      <div className="grid gap-4 md:grid-cols-3">
        <div className="rounded-xl border bg-card p-5">
          <p className="text-sm text-muted-foreground">Books Recommended</p>
          <p className="mt-2 text-3xl font-bold">{books.length}</p>
        </div>

        <div className="rounded-xl border bg-card p-5">
          <p className="text-sm text-muted-foreground">Recommendation Type</p>
          <p className="mt-2 text-lg font-semibold">Hybrid AI</p>
        </div>

        <div className="rounded-xl border bg-card p-5">
          <p className="text-sm text-muted-foreground">Personalization</p>
          <p className="mt-2 text-lg font-semibold">Reading Style + FAISS</p>
        </div>
      </div>

      {/* Recommendation Grid */}
      {loading ? (
        <div className="py-24 text-center">
          <div className="mx-auto h-10 w-10 animate-spin rounded-full border-b-2 border-primary" />
          <p className="mt-4 text-muted-foreground">
            Generating your recommendations...
          </p>
        </div>
      ) : books.length === 0 ? (
        <div className="rounded-xl border border-dashed py-20 text-center">
          <Sparkles className="mx-auto mb-4 h-10 w-10 text-muted-foreground" />
          <h3 className="text-lg font-semibold">No recommendations yet</h3>
          <p className="mt-2 text-sm text-muted-foreground">
            Complete onboarding or interact with more books to improve your
            recommendations.
          </p>
        </div>
      ) : (
        <div className="grid gap-6 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4">
          {books.map((book) => (
            <RecommendationCard
              key={book.isbn}
              book={book}
            />
          ))}
        </div>
      )}
    </div>
  );
}